#!/usr/bin/env node
// Builds client.js, the one file DeepSeek Harness loads in the browser, from the parts in client/.
//
// The browser half grew past what one file reads well (a header popover, a progress page, conversation rows), so it is
// written as parts, one per surface, and joined here in name order inside the module factory DeepSeek Harness expects.
// Nothing is transformed: the parts are plain JavaScript that share one scope, and client.js is their concatenation.
//
//   node scripts/build-client.mjs           writes client.js
//   node scripts/build-client.mjs --check   exits 1 when client.js is not what the parts build (the test suite runs this)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const partsDir = join(root, 'client')
const target = join(root, 'client.js')

export function buildClient() {
  const parts = readdirSync(partsDir).filter((name) => name.endsWith('.js')).sort()
  const body = parts.map((name) => {
    const source = readFileSync(join(partsDir, name), 'utf8').replace(/\s+$/, '')
    const indented = source.split('\n').map((line) => (line ? `    ${line}` : '')).join('\n')
    return `    // ---- client/${name} ----\n${indented}`
  }).join('\n\n')
  return [
    '// GENERATED by scripts/build-client.mjs from client/*.js. Edit the parts, then run `npm run build`.',
    '//',
    '// The browser half of the plugin: the AWR status light in the conversation header with its popover, the progress page',
    '// beside Chat and Trajectory, and the folded rows of `/awr` commands in the conversation. Plain JavaScript against the',
    "// module table's React, as DeepSeek Harness's plugin guide prescribes.",
    'window.__ModuleLoader__.load({',
    "  id: '@originoneai/dsh-awr',",
    '  factory(require) {',
    "    const React = require('react')",
    "    const ReactDOM = require('react-dom')",
    '    const h = React.createElement',
    '',
    body,
    '  },',
    '})',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const built = buildClient()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(target, 'utf8')
    } catch {
      current = ''
    }
    if (current !== built) {
      console.error('client.js is not what client/*.js builds. Run: npm run build')
      process.exit(1)
    }
  } else {
    writeFileSync(target, built)
    console.log(`client.js written (${built.length} bytes)`)
  }
}
